<?php
/**
 * Markdown template for wp-documentor, which lists the hooks sorted.
 *
 * wp-documentor lists the hooks in the order it finds the files - which is
 * the order of the file system and can differ between two computers. The
 * workflow "Hook documentation" would then commit a reordered docs/hooks.md
 * without any change of a hook. This template sorts the hooks by their name,
 * then by their file and line, and uses the template part of wp-documentor
 * for each hook - so the result is the same as with --format=markdown.
 *
 * Usage:
 * vendor/bin/wp-documentor parse src --format=markdown --template=bin/wp-documentor-markdown.php --relative=docs --output=docs/hooks.md
 *
 * @package crypt-for-wordpress
 */

namespace Pronamic\WordPress\Documentor;

if ( ! isset( $documentor ) ) {
	return;
}

/**
 * Return the given hooks sorted by their name, file and line.
 *
 * @param array<int,Hook> $hooks The hooks.
 *
 * @return array<int,Hook>
 */
$crypt_for_wordpress_sort_hooks = static function ( array $hooks ) use ( $documentor ): array {
	usort(
		$hooks,
		static function ( Hook $a, Hook $b ) use ( $documentor ): int {
			return array( $a->get_tag()->get_name(), $documentor->relative( $a->get_file() ), $a->get_start_line() )
				<=> array( $b->get_tag()->get_name(), $documentor->relative( $b->get_file() ), $b->get_start_line() );
		}
	);

	return $hooks;
};

$actions = $crypt_for_wordpress_sort_hooks( $documentor->get_actions() );
$filters = $crypt_for_wordpress_sort_hooks( $documentor->get_filters() );

// the template part of wp-documentor for a single hook.
$crypt_for_wordpress_hook_part = \dirname( (string) ( new \ReflectionClass( Documentor::class ) )->getFileName(), 2 ) . '/templates/parts/markdown-hook.php';

$eol = "\n";

echo '# Hooks', $eol;
echo $eol;
echo '- [Actions](#actions)', $eol;
echo '- [Filters](#filters)', $eol;
echo $eol;

echo '## Actions', $eol;
echo $eol;

if ( empty( $actions ) ) {
	echo '*This project does not contain any WordPress actions.*', $eol;
	echo $eol;
} else {
	foreach ( $actions as $hook ) {
		include $crypt_for_wordpress_hook_part;
	}
}

echo '## Filters', $eol;
echo $eol;

if ( empty( $filters ) ) {
	echo '*This project does not contain any WordPress filters.*', $eol;
	echo $eol;
} else {
	foreach ( $filters as $hook ) {
		include $crypt_for_wordpress_hook_part;
	}
}

echo $eol;
echo '<p align="center"><em>Generated by <a href="https://github.com/pronamic/wp-documentor">Pronamic WordPress Documentor</a></em></p>', $eol;
